print(f"The value of b is {b} and type of b is {type(b)}")
c = "Heyyy"
print(f"The value of c is {c} and type of c is {type(c)}")
d = False
print(f"The value of d is {d} and type of d is {type(d)}")
e = [1,2,3,4]
print(f"The value of e is {e} and type of e is {type(e)}")
f = (56,87,43,78)
print(f"The value of f is {f} and type of f is {type(f)}")
