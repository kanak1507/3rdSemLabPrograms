#String Operations in python
a = "hello"
b = "world "
c = "This is a String"
print(f"Value of a and b are {a} and {b} respectively")
print(f"Concatenation: {a +' '+ b}")
print(f"Uppercase: {a.upper()}")
print(f"Lowercase: {a.lower()}")
print(f"Length: {len(a)}")
print(f"Right Strip: {b.rstrip()}")
print(f"Startswith 'This': {c.startswith('This')}")
print(f"Endswith 'This': {c.endswith('This')}")